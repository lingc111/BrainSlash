import type { TriviaFact } from './ContentCatalog';

type FactPair = readonly [prompt: string, answer: string];

function expand(groups: readonly (readonly FactPair[])[]): readonly TriviaFact[] {
    return groups.flatMap((group) => group.map(([prompt, answer], index) => ({
        prompt,
        answer,
        wrong: group.filter((_, candidateIndex) => candidateIndex !== index).map((item) => item[1]),
    })));
}

