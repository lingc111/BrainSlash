export type HanziRelationKind = 'antonym' | 'synonym';

export interface HanziRelationFact {
    id: string;
    kind: HanziRelationKind;
    left: string;
    right: string;
    leftDistractors: readonly string[];
    rightDistractors: readonly string[];
}

type Pair = readonly [string, string];

function expandGroups(kind: HanziRelationKind, groups: readonly (readonly Pair[])[]): HanziRelationFact[] {
    const facts: HanziRelationFact[] = [];
    groups.forEach((group, groupIndex) => group.forEach(([left, right], pairIndex) => {
        facts.push({
            id: `hanzi.${kind}.${String(groupIndex * 5 + pairIndex + 1).padStart(3, '0')}`,
            kind,
            left,
            right,
            leftDistractors: group.filter((_, index) => index !== pairIndex).map((pair) => pair[0]),
            rightDistractors: group.filter((_, index) => index !== pairIndex).map((pair) => pair[1]),
        });
    }));
    return facts;
}

